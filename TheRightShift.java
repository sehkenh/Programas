public class TheRightShift {
    /*

        When a value has bits that are "shifted off", those bits are lost. For example, the next code
        fragment shifts the value of 3 to the right two positions, which causes the two low-order bits
        to be lost, resulting again in a being set to 8:

        int a = 35;
        a = a >> 2; //a now contains 8

        looking at the same operation in binary shows more clearly how this happens:

        00100011    35
        >> 2
        00001000    8

     */
}
